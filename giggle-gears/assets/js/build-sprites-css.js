// Generates assets/css/sprites.css and assets/js/sprites.js from the
// sprite-sheet JSON metadata.
//
//   node build-sprites-css.js
//
// DOM shape used by sprites:
//
//   <span class="sprite sprite-NAME"><img class="sprite-img" src="SHEET"></span>
//
// The wrapper sets aspect-ratio + CSS vars (--sw / --lx / --ty); the inner
// <img> renders the entire sheet at proportional size and is positioned so
// only the desired frame is visible inside the wrapper's overflow:hidden.
// This preserves the sprite's aspect ratio regardless of the wrapper's
// outer dimensions (set by the consumer's CSS).

const fs   = require('fs');
const path = require('path');

// Sprites.js builds <img src=> attributes that get attached to the document,
// so the URL is resolved relative to index.html. Using a relative path makes
// this work regardless of the deployed folder name (giggle_gears_v2 vs
// giggle-gears_v2 has tripped us up before).
const SHEET_BASE_JS = 'https://fymz.lol/giggle-gears/assets/sprite-sheets/';
const SHEETS_DIR = path.join(__dirname, 'assets', 'sprite-sheets');
const CSS_OUT    = path.join(__dirname, 'assets', 'css', 'sprites.css');
const JS_OUT     = path.join(__dirname, 'assets', 'js', 'sprites.js');

const sheets = [
    'button-icons',
    'driver-icons',
    'car-bodies',
    'npc-cars',
    'bg-sky',
];

const fmt = n => Number.isInteger(n) ? String(n) : n.toFixed(4).replace(/\.?0+$/, '');

let css = '/* Auto-generated by build-sprites-css.js — do not edit by hand. */\n\n';
css += '.sprite {\n';
css += '    display: block;\n';
css += '    overflow: hidden;\n';
css += '    position: relative;\n';
css += '    line-height: 0;\n';
css += '}\n';
css += '.sprite > .sprite-img {\n';
css += '    position: absolute;\n';
css += '    width: var(--sw);\n';
css += '    height: auto;\n';
css += '    left: var(--lx);\n';
css += '    top: var(--ty);\n';
css += '    pointer-events: none;\n';
css += '    user-select: none;\n';
css += '    -webkit-user-drag: none;\n';
css += '}\n\n';

const spriteSheetMap = {};

for (const name of sheets) {
    const json = JSON.parse(fs.readFileSync(path.join(SHEETS_DIR, name + '.json'), 'utf8'));
    const sW = json.meta.size.w;
    const sH = json.meta.size.h;

    css += `/* ── ${name} (${sW}×${sH}) ─────────────────────────────────────── */\n`;

    for (const [frameName, def] of Object.entries(json.frames)) {
        const { x: fX, y: fY, w: fW, h: fH } = def.frame;
        const sw = (sW / fW) * 100;
        const lx = -(fX / fW) * 100;
        const ty = -(fY / fH) * 100;

        css += `.sprite-${frameName} {\n`;
        css += `    aspect-ratio: ${fW} / ${fH};\n`;
        css += `    --sw: ${fmt(sw)}%;\n`;
        css += `    --lx: ${fmt(lx)}%;\n`;
        css += `    --ty: ${fmt(ty)}%;\n`;
        css += `    --fw: ${fW}px;\n`;
        css += `    --fh: ${fH}px;\n`;
        css += `}\n`;

        spriteSheetMap[frameName] = name;
    }
    css += '\n';
}

fs.writeFileSync(CSS_OUT, css);
console.log('Wrote', CSS_OUT, '(' + css.length + ' bytes)');

// ── JS helper ────────────────────────────────────────────────────────
let js = '// Auto-generated by build-sprites-css.js — do not edit by hand.\n\n';
js += 'const SHEET_URLS = {\n';
for (const name of sheets) {
    js += `    '${name}': '${SHEET_BASE_JS}${name}.png',\n`;
}
js += '};\n\n';

js += 'const SPRITE_SHEET = {\n';
for (const [frame, sheet] of Object.entries(spriteSheetMap)) {
    js += `    '${frame}': '${sheet}',\n`;
}
js += '};\n\n';

js += `function _sheetFor(name) {\n`;
js += `    const sheet = SPRITE_SHEET[name];\n`;
js += `    if (!sheet) throw new Error('Unknown sprite: ' + name);\n`;
js += `    return SHEET_URLS[sheet];\n`;
js += `}\n\n`;

js += `// Returns an HTML string for the given sprite. Optional extraClass / attrs\n`;
js += `// are spliced onto the wrapper.\n`;
js += `export function spriteHTML(name, { extraClass = '', attrs = '' } = {}) {\n`;
js += `    const src = _sheetFor(name);\n`;
js += `    const cls = ('sprite sprite-' + name + ' ' + extraClass).trim();\n`;
js += `    return \`<span class="\${cls}" \${attrs}><img class="sprite-img" src="\${src}" alt="" draggable="false"></span>\`;\n`;
js += `}\n\n`;

js += `// Builds and returns a sprite wrapper element.\n`;
js += `export function makeSpriteEl(name, extraClass = '') {\n`;
js += `    const span = document.createElement('span');\n`;
js += `    span.className = ('sprite sprite-' + name + ' ' + extraClass).trim();\n`;
js += `    const img = document.createElement('img');\n`;
js += `    img.className = 'sprite-img';\n`;
js += `    img.src = _sheetFor(name);\n`;
js += `    img.alt = '';\n`;
js += `    img.draggable = false;\n`;
js += `    span.appendChild(img);\n`;
js += `    return span;\n`;
js += `}\n`;

fs.writeFileSync(JS_OUT, js);
console.log('Wrote', JS_OUT, '(' + js.length + ' bytes)');
